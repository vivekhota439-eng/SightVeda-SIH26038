def translate_report(grade: int, lang_code: str = "hi") -> dict:
    """
    Returns localized strings for the specified clinical grade and language code.
    Fallback to English if language not supported.
    """
    code = lang_code.lower() if lang_code else "en"
    if code not in ["en", "hi", "mr", "ta", "te", "bn", "tcy"]:
        code = "en"
        
    grade = max(0, min(4, int(grade)))
    
    t_grade = TRANSLATIONS_7_LANG["grades"][grade].get(code, TRANSLATIONS_7_LANG["grades"][grade]["en"])
    t_urgency = TRANSLATIONS_7_LANG["urgency"][grade].get(code, TRANSLATIONS_7_LANG["urgency"][grade]["en"])
    t_etiology = TRANSLATIONS_7_LANG["etiology"][grade].get(code, TRANSLATIONS_7_LANG["etiology"][grade]["en"])
    t_lifting = TRANSLATIONS_7_LANG["lifting"][grade].get(code, TRANSLATIONS_7_LANG["lifting"][grade]["en"])
    t_referral = TRANSLATIONS_7_LANG["referral"][grade].get(code, TRANSLATIONS_7_LANG["referral"][grade]["en"])
    
    parhez_list = []
    for item in TRANSLATIONS_7_LANG["parhez"][grade]:
        parhez_list.append(item.get(code, item["en"]))
        
    return {
        "lang_code": code,
        "grade_title": t_grade,
        "urgency": t_urgency,
        "etiology": t_etiology,
        "lifting_restriction": t_lifting,
        "referral_facility": t_referral,
        "parhez": parhez_list
    }
